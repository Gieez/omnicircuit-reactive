const fs = require('fs');
const path = require('path');
const solc = require('solc');

function findImports(importPath) {
  let fullPath;
  if (importPath.startsWith('./') || importPath.startsWith('../')) {
    fullPath = path.resolve(__dirname, '../contracts', importPath);
  } else {
    fullPath = path.resolve(__dirname, '../contracts', importPath);
  }

  if (fs.existsSync(fullPath)) {
    return { contents: fs.readFileSync(fullPath, 'utf8') };
  }
  return { error: 'File not found: ' + importPath };
}

const contractFiles = [
  'OriginPool.sol',
  'OmniCircuitReactive.sol',
  'OmniCircuitCallback.sol'
];

const sources = {};
contractFiles.forEach((file) => {
  const filePath = path.resolve(__dirname, '../contracts', file);
  sources[file] = {
    content: fs.readFileSync(filePath, 'utf8'),
  };
});

const input = {
  language: 'Solidity',
  sources,
  settings: {
    optimizer: {
      enabled: true,
      runs: 200,
    },
    outputSelection: {
      '*': {
        '*': ['abi', 'evm.bytecode', 'evm.deployedBytecode'],
      },
    },
  },
};

console.log('Compiling OmniCircuit contracts with solc...');
const output = JSON.parse(
  solc.compile(JSON.stringify(input), { import: findImports })
);

if (output.errors) {
  let hasError = false;
  output.errors.forEach((err) => {
    console.log(err.formattedMessage);
    if (err.severity === 'error') hasError = true;
  });
  if (hasError) {
    console.error('Compilation failed with errors.');
    process.exit(1);
  }
}

const outDir = path.resolve(__dirname, '../src/contracts');
fs.mkdirSync(outDir, { recursive: true });

const artifacts = {};
contractFiles.forEach((file) => {
  const contractName = file.replace('.sol', '');
  const data = output.contracts[file][contractName];
  const artifact = {
    contractName,
    abi: data.abi,
    bytecode: '0x' + data.evm.bytecode.object,
    deployedBytecode: '0x' + data.evm.deployedBytecode.object,
  };

  fs.writeFileSync(
    path.join(outDir, `${contractName}.json`),
    JSON.stringify(artifact, null, 2)
  );

  artifacts[contractName] = artifact;
  console.log(`Saved artifact: ${contractName}.json (bytecode size: ${artifact.bytecode.length / 2} bytes)`);
});

// Generate TypeScript definitions
let tsContent = '// Autogenerated by scripts/compile.js\n\n';
Object.entries(artifacts).forEach(([name, art]) => {
  tsContent += `export const ${name}_ABI = ${JSON.stringify(art.abi, null, 2)} as const;\n`;
  tsContent += `export const ${name}_BYTECODE = "${art.bytecode}" as const;\n\n`;
});

fs.writeFileSync(path.join(outDir, 'contractsABI.ts'), tsContent);
console.log('Successfully generated contractsABI.ts.');
